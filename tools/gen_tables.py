#!/usr/bin/env python3
"""Writes tables.h, the fixed-point tables Grains reads: run it after changing
a curve here, and commit both."""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def row(values, per_line=8):
    return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ","
                     for i in range(0, len(values), per_line))


def table(kind, name, values, comment):
    return f"// {comment}\nconst {kind} {name}[{len(values)}] = {{\n{row(values)}\n}};\n"


# A grain's window rises along a quarter of sin^2 (0 to 1 over 64 steps) and falls back.
window = [round(32767 * math.sin(math.pi / 2 * i / 64) ** 2) for i in range(65)]
# size: 10 ms to 2 s, exponential, in samples at 44.1 kHz, 32 steps and an end.
size = [round(44100 * 0.010 * 200 ** (i / 32)) for i in range(33)]
# Pan, left gain for pan 0 (left) .. 16 (right); right is the mirror. Constant
# power scaled to unity in the centre, so a centred grain plays at full level.
pan = [min(32767, round(32767 * math.sqrt(2) * math.cos(math.pi / 2 * i / 16))) for i in range(17)]
# Grain gain by overlap: 1 / sqrt(grains sounding), 1..20, times the window's
# make-up (sin^2 has an RMS of sqrt(3/8)), Q15: above unity, so i32.
WINDOW_MAKEUP = 1 / math.sqrt(3 / 8)
gain = [round(32767 * WINDOW_MAKEUP / math.sqrt(k)) for k in range(1, 21)]
# Semitones within an octave as Q16 ratios.
semitone = [round(65536 * 2 ** (k / 12)) for k in range(12)]

CHORDS = [
    ("off", [0]),
    ("dtun", [0]),                       # the root, each grain detuned (detune below)
    ("oct", [0, 12, 24]),
    ("5th", [0, 7, 12, 19, 24]),
    ("maj", [0, 4, 7, 12, 16, 19, 24]),
    ("min", [0, 3, 7, 12, 15, 19, 24]),
    ("harm", [12 * math.log2(k) for k in range(1, 9)]),
]
ratios, counts = [], []
for _, steps in CHORDS:
    r = [round(65536 * 2 ** (s / 12)) for s in steps]
    counts.append(len(r))
    ratios += r + [r[-1]] * (8 - len(r))
# dtun: each grain's offset in cents, as Q16 ratios.
detune = [round(65536 * 2 ** (c / 1200)) for c in (0, -14, 11, -7, 16, -18, 5, 9)]

out = ["#pragma once", "// Generated by tools/gen_tables.py; edit the generator, not this file.",
       "#include <opxy/types.hpp>", "", "namespace grains {", ""]
out += [table("opxy::i16", "window_table", window, "A grain window's rising quarter, Q15, 64 steps and an end."),
        table("opxy::u32", "size_table", size, "size: 10 ms to 2 s in samples, exponential, 32 steps and an end."),
        table("opxy::i16", "pan_table", pan, "Pan: the left gain, Q15, for pan 0..16; unity in the centre."),
        table("opxy::i32", "gain_table", gain, "Each grain's gain for 1..20 sounding: 1 / sqrt(n) and the window's make-up, Q15."),
        table("opxy::u32", "semitone_table", semitone, "2^(k/12) for k 0..11, Q16."),
        table("opxy::u32", "chord_table", ratios, "chrd: each grain's pitch ratio, Q16, 8 a chord: " +
              ", ".join(n for n, _ in CHORDS) + "."),
        table("opxy::u8", "chord_count", counts, "The notes in each chord; grain n plays note n mod count."),
        table("opxy::u32", "detune_table", detune, "dtun: each grain's offset from the root, Q16.")]
out += ["}", ""]
(ROOT / "tables.h").write_text("\n".join(out))
print("wrote", ROOT / "tables.h")
